import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import {
  aboutMetadata,
  defaultMetadata,
  homeMetadata,
} from "./site-metadata";

// Every page gets a descriptive title and description of its own instead of
// the framework's default text (home-redesign RF-34, WCAG 2.4.2).
const FRAMEWORK_DEFAULTS = /create next app|generated by create next app/i;

const ALL = { defaultMetadata, homeMetadata, aboutMetadata };

function titleText(title: unknown): string {
  if (typeof title === "string") return title;
  const { default: fallback, absolute } = title as {
    default?: string;
    absolute?: string;
  };
  return absolute ?? fallback ?? "";
}

describe("site metadata (RF-34)", () => {
  it("has a default title, a template for the pages that name themselves, and a description", () => {
    const title = defaultMetadata.title as { default: string; template: string };

    expect(title.default.length).toBeGreaterThan(0);
    expect(title.template).toContain("%s");
    expect(title.template).toContain(title.default);
    expect(typeof defaultMetadata.description).toBe("string");
  });

  it("gives the home a title and description of its own", () => {
    expect(titleText(homeMetadata.title)).not.toBe(
      titleText(defaultMetadata.title)
    );
    expect(homeMetadata.description).not.toBe(defaultMetadata.description);
    expect(homeMetadata.title).toHaveProperty("absolute");
  });

  it("gives the About page its own entry, completed by the template", () => {
    expect(aboutMetadata.title).toBe("About");
    expect(String(aboutMetadata.description).length).toBeGreaterThan(0);
  });

  it.each(Object.entries(ALL))("%s has no framework default text", (_name, metadata) => {
    expect(JSON.stringify(metadata)).not.toMatch(FRAMEWORK_DEFAULTS);
  });

  it.each(Object.entries(ALL))(
    "%s has a description of a useful length for a search result",
    (_name, metadata) => {
      const description = String(metadata.description);

      expect(description.length).toBeGreaterThanOrEqual(50);
      expect(description.length).toBeLessThanOrEqual(160);
    }
  );

  it("is in English (constitution §9): no accented letters or inverted marks", () => {
    expect(JSON.stringify(ALL)).not.toMatch(/[áéíóúñ¿¡]/i);
  });
});

describe("where the metadata is used", () => {
  it("the root layout exports the default metadata, not the framework's", () => {
    const layout = readFileSync("app/layout.tsx", "utf-8");

    expect(layout).toMatch(/import \{[^}]*defaultMetadata[^}]*\} from "\.\/site-metadata"/);
    expect(layout).toMatch(/export const metadata[^=]*= defaultMetadata/);
    expect(layout).not.toMatch(FRAMEWORK_DEFAULTS);
  });

  it("the home page exports its own metadata", () => {
    const page = readFileSync("app/page.tsx", "utf-8");

    expect(page).toMatch(/import \{[^}]*homeMetadata[^}]*\} from "\.\/site-metadata"/);
    expect(page).toMatch(/export const metadata[^=]*= homeMetadata/);
  });
});
